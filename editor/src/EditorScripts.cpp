void Workspace::RefreshScriptFiles(bool force)
{
    if(m_scriptListProject!=m_project) {
        m_scriptListProject=m_project;m_scriptFiles.clear();m_openScripts.clear();m_selectedScriptTab.clear();
        m_scriptScanAt=-1;m_sourceFilter[0]=0;m_findVisible=false;m_consoleHiddenPrefix.clear();
    }
    if(!force && m_scriptScanAt>=0 && ImGui::GetTime()-m_scriptScanAt<2.0)return;
    m_scriptScanAt=ImGui::GetTime();
    std::vector<std::filesystem::path> files;
    if(!m_project.empty()) {
        auto iterator=std::filesystem::recursive_directory_iterator(m_project,std::filesystem::directory_options::skip_permission_denied);
        size_t visited=0;
        for(const auto end=std::filesystem::recursive_directory_iterator{};iterator!=end;++iterator) {
            const auto& entry=*iterator;
            if(++visited>20000)break;
            const auto name=FoldCase(Utf8Text(entry.path().filename()));
            if(entry.is_directory()) {
                if(entry.is_symlink() || iterator.depth()>=16 || name.starts_with(".") || name=="bin" || name=="node_modules" ||
                   name=="build" || name.starts_with("build-") || name=="cmakefiles")iterator.disable_recursion_pending();
                continue;
            }
            const auto extension=FoldCase(Utf8Text(entry.path().extension()));
            if(entry.is_regular_file() && (extension==".cx" || extension==".cpp" || extension==".h" || extension==".hpp" || extension==".scene" || extension==".yu" || name=="concord.project") && IsProjectFile(m_project,entry.path()))files.push_back(entry.path());
        }
    }
    std::sort(files.begin(),files.end(),[](const auto& a,const auto& b){return FoldCase(Utf8Text(a))<FoldCase(Utf8Text(b));});
    m_generatedScripts.clear();
    for(const auto& file:files)if(IsGenerated(file))m_generatedScripts.push_back(file);
    m_scriptFiles=std::move(files);
}

