std::string FoldCase(std::string text)
{
    for(char& c:text)if(static_cast<unsigned char>(c)<128)c=static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    return text;
}
bool ContainsText(const std::string& text,const char* query)
{
    return !query[0] || FoldCase(text).find(FoldCase(query))!=std::string::npos;
}
bool IsGenerated(const std::filesystem::path& path)
{
    const auto name=FoldCase(Utf8Text(path.filename()));
    return (name=="scenelayout.cx" || name=="projectruntime.cx") && ReadText(path).starts_with("// Generated by Concord Editor.");
}
bool IsProjectFile(const std::filesystem::path& root,const std::filesystem::path& path)
{
    const auto canonicalRoot=std::filesystem::weakly_canonical(root);
    const auto canonicalFile=std::filesystem::weakly_canonical(path);
    auto part=canonicalFile.begin();
    for(const auto& expected:canonicalRoot) {
        if(part==canonicalFile.end() || CompareStringOrdinal(expected.c_str(),-1,part->c_str(),-1,TRUE)!=CSTR_EQUAL)return false;
        ++part;
    }
    return part!=canonicalFile.end();
}
bool HasDiagnostic(const std::string& line)
{
    const auto text=FoldCase(line);
    return text.find("error")!=std::string::npos || text.find("warning")!=std::string::npos || text.find("failed")!=std::string::npos;
}
std::string ValidScriptName(std::string name)
{
    if(name.size()>3 && FoldCase(name.substr(name.size()-3))==".cx")name.resize(name.size()-3);
    if(name.empty() || name.size()>100 || !(std::isalpha(static_cast<unsigned char>(name[0])) || name[0]=='_'))
        throw std::runtime_error(Tr("Start with a letter or underscore; use a ConcordScript identifier."));
    for(unsigned char c:name)if(c>=128 || !(std::isalnum(c) || c=='_'))
        throw std::runtime_error(Tr("Use letters, numbers and underscores. Folder paths are not allowed."));
    const auto folded=FoldCase(name);
    if(folded=="con" || folded=="prn" || folded=="aux" || folded=="nul" ||
       (folded.size()==4 && (folded.starts_with("com") || folded.starts_with("lpt")) && folded[3]>='1' && folded[3]<='9'))
        throw std::runtime_error(Tr("This name is reserved by Windows."));
    if(folded=="scenelayout" || folded=="projectruntime")throw std::runtime_error(Tr("This name is used by a generated file; choose another name."));
    return name;
}
void WriteNewSource(const std::filesystem::path& path,const std::string& text)
{
    const HANDLE file=CreateFileW(path.c_str(),GENERIC_WRITE,0,nullptr,CREATE_NEW,FILE_ATTRIBUTE_NORMAL,nullptr);
    if(file==INVALID_HANDLE_VALUE) {
        if(GetLastError()==ERROR_FILE_EXISTS || GetLastError()==ERROR_ALREADY_EXISTS)
            throw std::runtime_error(Tr("A file with this name already exists. Existing source is never overwritten."));
        throw std::runtime_error("Cannot create source file (Windows error "+std::to_string(GetLastError())+").");
    }
    DWORD written=0;
    const bool okay=WriteFile(file,text.data(),static_cast<DWORD>(text.size()),&written,nullptr) && written==text.size() && FlushFileBuffers(file);
    CloseHandle(file);
    if(!okay) {
        DeleteFileW(path.c_str());
        throw std::runtime_error(Tr("Cannot finish writing the new script."));
    }
}
const char* FileIcon(const std::filesystem::path& file,bool generated)
{
    const auto extension=FoldCase(Utf8Text(file.extension()));
    if(extension==".scene")return "cube";
    if(extension==".yu")return "grid";
    if(extension==".project")return "settings";
    return generated?"code":"file";
}
